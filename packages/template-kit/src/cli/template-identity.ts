/**
 * Per-template identity for the dashboard picker (giro, art direction, palette swatches, Pro-only
 * features), read from the kit so the API and the database need nothing new. Written by
 * `kit:manifest` to apps/web/src/features/templates/template-identity.generated.ts.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import * as prettier from 'prettier';
import type { CatalogManifest } from '../../catalog/types';
import { DIRECTIONS } from '../../directions';
import { GIROS } from '../../giros';
import { listManifestFiles, loadManifest, loadTheme } from '../lib/load';
import { KIT_ROOT, REPO_ROOT } from '../lib/paths';

export const WEB_TEMPLATE_IDENTITY_FILE = resolve(
  REPO_ROOT,
  'apps/web/src/features/templates/template-identity.generated.ts',
);

/** es-MX names for the Pro-only pieces a template carries (by `slot/variant`, then by slot). */
const FEATURE_LABELS: Record<string, string> = {
  'hero/bento': 'Portada con cifras',
  gallery: 'Galería',
  testimonials: 'Testimonios',
  team: 'Equipo',
  marquee: 'Cinta en movimiento',
  about: 'Nosotros Pro',
  locations: 'Contacto con mapa',
};
const MOTION_LABEL = 'Animaciones';

export interface TemplateIdentity {
  id: string;
  tier: 'basic' | 'pro';
  giro: string;
  giroLabel: string;
  direction: { id: string; name: string } | null;
  /** bg, surface, accent, text: enough to recognize the palette at a glance. */
  swatches: string[];
  dark: boolean;
  proFeatures: string[];
}

function specDirection(file: string): string | null {
  const first = readFileSync(file, 'utf8').split('\n', 1)[0];
  const stem = /GENERATED from (specs\/[^\s]+\.spec\.json)/.exec(first)?.[1];
  if (!stem) return null;
  const spec = JSON.parse(readFileSync(resolve(KIT_ROOT, stem), 'utf8')) as {
    layout?: { direction?: string };
  };
  return spec.layout?.direction ?? null;
}

function luminance(hex: string): number {
  const m = /^#([0-9a-f]{6})$/i.exec(hex);
  if (!m) return 1;
  const [r, g, b] = [0, 2, 4].map(
    (i) => parseInt(m[1].slice(i, i + 2), 16) / 255,
  );
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export async function buildTemplateIdentities(
  m: CatalogManifest,
): Promise<TemplateIdentity[]> {
  const proOnly = new Set(
    m.variants.filter((v) => v.proOnly).map((v) => v.key),
  );
  const out: TemplateIdentity[] = [];
  for (const file of listManifestFiles()) {
    const manifest = await loadManifest(file);
    const theme = loadTheme(manifest.theme);
    const directionId = specDirection(file);
    const direction = directionId ? DIRECTIONS[directionId] : undefined;
    const features = new Set<string>();
    for (const s of manifest.sections) {
      const key = `${s.slot}/${s.variant}`;
      if (!proOnly.has(key)) continue;
      features.add(FEATURE_LABELS[key] ?? FEATURE_LABELS[s.slot] ?? key);
    }
    if (manifest.tier === 'pro') features.add(MOTION_LABEL);
    const c = theme.colors;
    out.push({
      id: manifest.id,
      tier: manifest.tier,
      giro: manifest.vertical,
      giroLabel: GIROS[manifest.vertical]?.label ?? manifest.vertical,
      direction: direction ? { id: direction.id, name: direction.name } : null,
      swatches: [c.bg, c.surface, c.accent, c.text],
      dark: luminance(c.bg) < 0.4,
      proFeatures: [...features],
    });
  }
  return out.sort((a, b) => a.id.localeCompare(b.id));
}

export async function renderTemplateIdentities(
  m: CatalogManifest,
): Promise<string> {
  const list = await buildTemplateIdentities(m);
  const config = await prettier.resolveConfig(WEB_TEMPLATE_IDENTITY_FILE);
  return prettier.format(
    `// GENERATED by \`pnpm --filter @lattiz/template-kit kit:manifest\` from packages/template-kit (templates, themes, specs). Do not edit.\n\nexport interface TemplateIdentity {\n  id: string;\n  tier: 'basic' | 'pro';\n  giro: string;\n  giroLabel: string;\n  direction: { id: string; name: string } | null;\n  swatches: string[];\n  dark: boolean;\n  proFeatures: string[];\n}\n\n/** Kit templates by id: giro, art direction, palette swatches and Pro-only features. */\nexport const TEMPLATE_IDENTITIES: TemplateIdentity[] = ${JSON.stringify(list, null, 2)};\n`,
    { ...(config ?? {}), parser: 'typescript' },
  );
}
