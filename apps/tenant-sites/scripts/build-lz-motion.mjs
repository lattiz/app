// Minifies lib/lz-motion/src into lib/lz-motion/runtime.generated.ts (committed).
// Run after editing the runtime: pnpm --filter @lattiz/tenant-sites build:motion
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { transform } from 'esbuild';

const MAX_GZIP_BYTES = 12 * 1024;
const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'lib', 'lz-motion');

const js = await transform(readFileSync(join(dir, 'src/runtime.js'), 'utf8'), {
  loader: 'js',
  minify: true,
  target: 'es2017',
  legalComments: 'none',
});
const css = await transform(readFileSync(join(dir, 'src/style.css'), 'utf8'), {
  loader: 'css',
  minify: true,
});
const code = js.code.trim();
const style = css.code.trim();

if (/<\/script/i.test(code) || /<\/style/i.test(style)) {
  throw new Error('Minified output contains a closing tag and cannot be inlined.');
}
const gzip = gzipSync(code + style, { level: 9 }).length;
if (gzip > MAX_GZIP_BYTES) {
  throw new Error(`lz-motion is ${gzip} bytes gzipped; the budget is ${MAX_GZIP_BYTES}.`);
}

writeFileSync(
  join(dir, 'runtime.generated.ts'),
  `// Generated by scripts/build-lz-motion.mjs from lib/lz-motion/src — do not edit.\n` +
    `// ${code.length + style.length} bytes minified, ${gzip} bytes gzipped.\n` +
    `export const LZ_MOTION_JS = ${JSON.stringify(code)};\n` +
    `export const LZ_MOTION_CSS = ${JSON.stringify(style)};\n`,
);
console.log(`lz-motion: ${code.length + style.length} B minified, ${gzip} B gzipped (budget ${MAX_GZIP_BYTES}).`);
